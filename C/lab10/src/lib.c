/**
 * @file lib.c
 * @brief Реалізація функцій для роботи з матрицями та масивами.
 *
 * Цей файл містить логіку виділення пам'яті, обробки матриць
 * (отримання діагоналі) та сортування масивів.
 * Всі операції доступу до даних виконуються через арифметику вказівників.
 *
 * @author Yaroslav Shepelia
 * @date 2025-11-23
 */

#include "lib.h"
#include <stdlib.h>

/**
 * @brief Виділяє динамічну пам'ять під квадратну матрицю (N x N).
 *
 * Функція спочатку виділяє пам'ять під масив вказівників (рядки),
 * а потім у циклі виділяє пам'ять під кожен окремий рядок.
 *
 * @note Якщо під час виділення пам'яті станеться помилка (malloc поверне NULL),
 * функція коректно звільнить всю вже виділену пам'ять, щоб уникнути витоків (memory leaks).
 *
 * @param size Розмірність матриці (кількість рядків і стовпчиків).
 * @return int** Вказівник на створену матрицю або NULL, якщо пам'ять не вдалося виділити.
 */
int** create_matrix(size_t size) {
	// Виділяємо масив вказівників 
    int** matrix = (int**)malloc(size * sizeof(int*));
    if (!matrix) return NULL;

    for (size_t i = 0; i < size; i++) {
        // Виділяємо пам'ять під кожен рядок: *(matrix + i)
        *(matrix + i) = (int*)malloc(size * sizeof(int));
        
        // Якщо помилка виділення пам'яті
        if (!*(matrix + i)) {
            // Очищаємо все, що встигли виділити раніше
            while (i > 0) {
                i--;
                free(*(matrix + i));
            }
            free(matrix);
            return NULL;
        }
    }
    return matrix;
}

/**
 * @brief Звільняє пам'ять, виділену під матрицю.
 *
 * Функція проходить по всіх рядках матриці, звільняючи їх,
 * а потім звільняє основний масив вказівників.
 *
 * @param matrix Вказівник на матрицю, яку треба видалити.
 * @param size Розмірність матриці (потрібна для циклу).
 */
void free_matrix(int** matrix, size_t size) {
    if (!matrix) return;
    for (size_t i = 0; i < size; i++) {
        free(*(matrix + i)); // Звільняємо рядок i
    }
    free(matrix); // Звільняємо масив вказівників
}

/**
 * @brief Записує елементи головної діагоналі матриці у одновимірний масив.
 *
 * Головна діагональ складається з елементів, де індекс рядка дорівнює індексу стовпчика (i, i).
 * Функція використовує арифметику вказівників (*(*(matrix + i) + i)) замість індексування [].
 *
 * @param matrix Вхідна матриця (джерело даних).
 * @param size Розмірність матриці.
 * @param out_array Вказівник на попередньо виділений масив, куди буде записано результат.
 */
void get_diagonal(int** matrix, size_t size, int* out_array) {
    for (size_t i = 0; i < size; i++) {
        int value = *(*(matrix + i) + i);
        *(out_array + i) = value;
    }
}

/**
 * @brief Сортує масив цілих чисел за зростанням.
 *
 * Використовується алгоритм сортування бульбашкою (Bubble Sort).
 * Доступ до елементів та їх обмін здійснюється через вказівники.
 *
 * @param array Вказівник на масив, який потрібно відсортувати.
 * @param size Кількість елементів у масиві.
 */
void sort_array(int* array, size_t size) {
    if (size < 2) return;

    for (size_t i = 0; i < size - 1; i++) {
        for (size_t j = 0; j < size - i - 1; j++) {
            int val_curr = *(array + j);
            int val_next = *(array + j + 1);

            if (val_curr > val_next) {
                *(array + j) = val_next;
                *(array + j + 1) = val_curr;
            }
        }
    }
}