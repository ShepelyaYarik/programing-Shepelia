/**
 * @file list.h
 * @brief Містить оголошення класу-колекції PhoneList.
 * * Реалізує динамічний масив вказівників для зберігання поліморфних об'єктів.
 */

#ifndef LIST_H
#define LIST_H

#include "entity.h"
#include <cstddef>

/**
 * @class PhoneList
 * @brief Клас-колекція, що інкапсулює динамічний масив вказівників на MobilePhone.
 * * Клас самостійно керує виділеною пам'яттю. Він автоматично розширюється при 
 * додаванні нових елементів та звільняє пам'ять об'єктів у деструкторі.
 */
class PhoneList {
private:
    MobilePhone** phones; ///< Динамічний масив вказівників на базовий клас.
    size_t count;         ///< Поточна кількість елементів у списку.
    size_t capacity;      ///< Максимальна місткість виділеного масиву до наступного розширення.

    /**
     * @brief Приватний метод для збільшення місткості масиву.
     * Викликається автоматично, коли count == capacity.
     */
    void resize();

public:
    /**
     * @brief Конструктор за замовчуванням.
     * Виділяє початкову пам'ять для масиву вказівників.
     */
    PhoneList();

    /**
     * @brief Деструктор колекції.
     * Очищає пам'ять, викликаючи delete для кожного об'єкта MobilePhone,
     * а потім видаляє сам масив вказівників. Запобігає витокам пам'яті.
     */
    ~PhoneList();

    /**
     * @brief Додає новий телефон у список.
     * @param phone Вказівник на створений об'єкт (MobilePhone, ButtonPhone або FoldablePhone).
     * @param pos Позиція (індекс), на яку потрібно вставити елемент. За замовчуванням = 0.
     * * @note Об'єкт має бути створений через оператор `new`. Клас PhoneList бере на себе 
     * відповідальність за його видалення.
     */
    void addPhone(MobilePhone* phone, size_t pos = 0);

    /**
     * @brief Видаляє телефон зі списку за індексом.
     * @param index Індекс елемента для видалення.
     * @throw std::out_of_range Якщо індекс виходить за межі [0, count-1].
     */
    void removePhone(size_t index);
    
    /**
     * @brief Виводить у консоль інформацію про всі телефони у списку.
     */
    void printAll() const;

    /**
     * @brief Обчислює загальний об'єм оперативної пам'яті всіх телефонів у колекції.
     * @return Загальний об'єм RAM у мегабайтах.
     */
    int calculateTotalRAM() const;

    /**
     * @brief Знаходить та виводить усі кнопкові телефони, які НЕ є "бабусяфонами".
     * Використовує dynamic_cast для фільтрації потрібних спадкоємців.
     */
    void printNonBabushkaButtonPhones() const;

    /**
     * @brief Знаходить та виводить усі складані телефони (FoldablePhone) у колекції.
     * Використовує dynamic_cast для ідентифікації складаних пристроїв.
     */
    void printFoldablePhones() const;
};

#endif // LIST_H