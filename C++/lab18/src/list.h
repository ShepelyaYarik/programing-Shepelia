/**
 * @file list.h
 * @brief Оголошення класу List для керування динамічною колекцією покажчиків на Phone.
 */

#ifndef LIST_H
#define LIST_H

#include "entity.h"
#include <cstddef>
#include <string>

/**
 * @class List
 * @brief Клас-контейнер, що керує динамічним масивом покажчиків на об'єкти Phone.
 * * Реалізує механізми безпечного додавання, видалення елементів, а також взаємодії
 * з файловими потоками введення/виведення без витоків пам'яті.
 */
class List {
private:
    Phone** data;  /**< Двовимірний динамічний масив (масив покажчиків на Phone) */
    size_t size;   /**< Поточна кількість елементів у списку */
    
    /**
     * @brief Внутрішній приватний метод для повної утилізації виділеної динамічної пам'яті.
     */
    void clear();

public:
    /**
     * @brief Конструктор за замовчуванням. Створює порожній список.
     */
    List();

    /**
     * @brief Деструктор класу List. Очищує пам'ять з-під контейнера та елементів.
     */
    ~List();

    /**
     * @brief Додає (вставляє) телефон у динамічний масив на задану індексом позицію.
     * @param phone Об'єкт телефону для копіювання та вставки.
     * @param pos Індекс позиції для вставки (якщо не передано — додає на початок, позиція 0).
     */
    void addPhone(const Phone& phone, size_t pos = 0);

    /**
     * @brief Видаляє телефон із динамічного масиву за його індексом.
     * @param index Індекс елемента, який необхідно видалити.
     * @throw std::out_of_range Якщо інндекс виходить за допустимі межі масиву.
     */
    void removePhone(size_t index);

    /**
     * @brief Отримує неконстантне посилання на телефон за його індексом для редагування.
     * @param index Індекс потрібного телефона.
     * @return Phone& Посилання на об'єкт телефона.
     * @throw std::out_of_range Якщо індекс виходить за допустимі межі масиву.
     */
    Phone& getPhone(size_t index);

    /**
     * @brief Отримує константне посилання на телефон за його індексом (режим тільки для читання).
     * @param index Індекс потрібного телефона.
     * @return const Phone& Константне посилання на об'єкт телефона.
     * @throw std::out_of_range Якщо індекс виходить за допустимі межі масиву.
     */
    const Phone& getPhone(size_t index) const; 

    /**
     * @brief Повертає поточну кількість елементів у колекції.
     * @return Кількість елементів типу size_t.
     */
    size_t getSize() const;

    /**
     * @brief Виводить увесь поточний список об'єктів у консоль за допомогою методу toString().
     */
    void print() const;

    /**
     * @brief Розраховує загальну суму оперативної пам'яті (RAM) серед усіх телефонів списку.
     * @return Індивідуальне завдання: Сумарний обсяг RAM у Мегабайтах.
     */
    int getTotalRam() const;

    /**
     * @brief Зчитує список об'єктів з текстового файлу за допомогою ifstream.
     * * При повторному читанні старі елементи контейнера автоматично видаляються з пам'яті.
     * @param fileName Шлях до файлу, з якого читаються дані.
     */
    void readFromFile(const std::string& fileName);

    /**
     * @brief Записує весь поточний масив об'єктів у текстовий файл за допомогою ofstream.
     * @param fileName Шлях до файлу для збереження даних.
     */
    void writeToFile(const std::string& fileName);
};

#endif // LIST_H