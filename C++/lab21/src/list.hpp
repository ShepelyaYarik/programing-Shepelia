/**
 * @file list.hpp
 * @brief Визначення та реалізація шаблонного класу-списку на базі динамічного масиву.
 *
 * Цей файл містить опис узагальненого контейнера List, який дозволяє зберігати
 * та обробляти елементи будь-якого типу даних, що підтримують оператори порівняння.
 */

#ifndef LIST_HPP
#define LIST_HPP

#include <iostream>
#include <stdexcept>
#include <cstddef>

using std::cout;
using std::endl;
using std::out_of_range;

/**
 * @class List
 * @brief Шаблонний клас-список на базі динамічного масиву.
 * * Забезпечує динамічне виділення пам'яті, додавання, видалення,
 * сортування та пошук елементів узагальненого типу.
 * * @tparam T Тип елементів, які зберігаються в списку (має підтримувати оператори >, <, == та вивід у потік).
 */
template <typename T>
class List {
private:
    T* data;          /**< Вказівник на динамічний масив елементів типу T */
    size_t capacity;  /**< Поточна загальна місткість виділеного масиву (місткість) */
    size_t size;      /**< Фактична кількість елементів, що зараз зберігаються у списку */

    /**
     * @brief Приватний метод для збільшення місткості масиву вдвічі.
     * * Викликається автоматично, коли кількість елементів (`size`) досягає
     * поточної місткості масиву (`capacity`). Виділяє нову пам'ять,
     * копіює старі дані та звільняє попередньо виділений блок.
     */
    void resize() {
        capacity = (capacity == 0) ? 1 : capacity * 2;
        T* newData = new T[capacity];
        for (size_t i = 0; i < size; ++i) {
            newData[i] = data[i];
        }
        delete[] data;
        data = newData;
    }

public:
    /**
     * @brief Конструктор за замовчуванням.
     * * Ініціалізує порожній список з нульовою місткістю та вказівником на nullptr.
     */
    List() : data(nullptr), capacity(0), size(0) {}

    /**
     * @brief Деструктор класу.
     * * Гарантовано звільняє виділену динамічну пам'ять масиву,
     * забезпечуючи відсутність витоків пам'яті (валідація Valgrind).
     */
    ~List() {
        delete[] data;
    }

    /**
     * @brief Додати елемент до кінця масиву.
     * * Якщо масив повністю заповнений, метод автоматично викликає внутрішній
     * метод `resize()` для розширення виділеної пам'яті.
     * * @param element Посилання на елемент типу T, який необхідно додати.
     */
    void append(const T& element) {
        if (size >= capacity) {
            resize();
        }
        data[size] = element;
        ++size;
    }

    /**
     * @brief Вивід вмісту масиву на екран.
     * * Послідовно обходить усі елементи масиву та виводить їх у стандартний
     * потік виведення через пробіл, завершуючи переходом на новий рядок.
     */
    void print() const {
        for (size_t i = 0; i < size; ++i) {
            cout << data[i] << " ";
        }
        cout << endl;
    }

    /**
     * @brief Визначити індекс переданого елемента в заданому масиві.
     * * Виконує лінійний пошук елемента в динамічному масиві.
     * * @param element Елемент типу T, індекс якого потрібно знайти.
     * @return int Повертає індекс елемента (від 0 до size-1), або -1, якщо елемент відсутній.
     */
    int indexOf(const T& element) const {
        for (size_t i = 0; i < size; ++i) {
            if (data[i] == element) {
                return static_cast<int>(i);
            }
        }
        return -1;
    }

    /**
     * @brief Визначити значення мінімального елемента масиву.
     * * Шукає найменший елемент у списку, спираючись на оператор порівняння `<` для типу T.
     * * @return T Значення мінімального елемента.
     * @throws std::out_of_range Якщо метод викликано для порожнього списку.
     */
    T min() const {
        if (size == 0) {
            throw out_of_range("List is empty");
        }
        T minVal = data[0];
        for (size_t i = 1; i < size; ++i) {
            if (data[i] < minVal) {
                minVal = data[i];
            }
        }
        return minVal;
    }

    /**
     * @brief Відсортувати елементи масиву.
     * * Виконує сортування елементів за зростанням за допомогою стійкого
     * алгоритму сортування бульбашкою (Bubble Sort) та оператора `>`.
     */
    void sort() {
        if (size < 2) return;
        for (size_t i = 0; i < size - 1; ++i) {
            for (size_t j = 0; j < size - i - 1; ++j) {
                if (data[j] > data[j + 1]) {
                    T temp = data[j];
                    data[j] = data[j + 1];
                    data[j + 1] = temp;
                }
            }
        }
    }

    /**
     * @brief Видалити елемент з масиву за індексом.
     * * Видаляє елемент за вказаною позицією, після чого зсуває всі наступні
     * елементи вліво на одну позицію для збереження цілісності масиву.
     * * @param index Позиція (індекс) елемента, який необхідно видалити.
     * @throws std::out_of_range Якщо переданий індекс виходить за межі [0, size-1].
     */
    void removeAt(size_t index) {
        if (index >= size) {
            throw out_of_range("Index out of bounds");
        }
        for (size_t i = index; i < size - 1; ++i) {
            data[i] = data[i + 1];
        }
        --size;
    }

    /**
     * @brief Геттер для поточної кількості елементів у списку.
     * * Використовується переважно у модульних тестах для перевірки динамічних змін розміру.
     * * @return size_t Кількість активних елементів у масиві.
     */
    size_t getSize() const {
        return size;
    }

    /**
     * @brief Перевантажений оператор доступу за індексом.
     * * Надає прямий доступ до елементів динамічного масиву з контролем меж.
     * * @param index Індекс необхідного елемента.
     * @return T& Посилання на елемент типу T за вказаним індексом.
     * @throws std::out_of_range Якщо переданий індекс поза межами поточного розміру списку.
     */
    T& operator[](size_t index) {
        if (index >= size) {
            throw out_of_range("Index out of bounds");
        }
        return data[index];
    }
};

#endif // LIST_HPP